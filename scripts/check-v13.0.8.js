const fs = require('node:fs');
const check = (ok, message) => { if (!ok) throw new Error(message); };
const read = file => fs.readFileSync(file, 'utf8');
const css = read('css/app.css');
const workspace = read('js/online-workspace.js');
const pkg = JSON.parse(read('package.json'));
const changelog = JSON.parse(read('changlog.json'));
check(css.includes('brightness(.52)') && css.includes('rgba(0,0,0,.66)'), 'Fullscreen background must be darkened for readable contrast over pale artwork.');
check(css.includes('background: rgba(8,8,11,.72) !important;'), 'Desktop controls panel must keep readable contrast without changing geometry.');
check(workspace.includes("return 'Streaming';") && !workspace.includes("return 'Online Music';"), 'Online playback context label must not show the generic Online Music label.');
check(changelog.entries.some(entry => entry.version === '13.0.8'), '13.0.8 release notes must remain in the changelog.');
check(/mujic-pwa-v13\.0\.\d+-machhar-beta-v1-9/.test(read('sw.js')), 'Service worker must use a versioned Machhar Beta v1.9 cache.');
console.log('v13.0.8 checks passed: fullscreen contrast, desktop panel contrast, source label, service-worker cache and release metadata.');
