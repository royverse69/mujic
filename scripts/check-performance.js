const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
const html = read('index.html');
const provider = read('js/online-provider.js');
const loader = read('js/module-loader.js');
const sw = read('sw.js');
const manifest = JSON.parse(read('manifest.webmanifest'));
const workspace = read('js/online-workspace.js');
const player = read('js/player.js');
const uiPlayer = read('js/ui-player.js');
const settings = read('js/ui-settings.js');
const appCss = read('css/app.css');
assert.match(provider, /options\.targetSize/);
assert.match(provider, /artworkMediumUrl: getImage\(raw, \{targetSize: 280\}\)/);
assert.match(provider, /artworkLargeUrl: getImage\(raw, \{targetSize: 640\}\)/);
assert.match(uiPlayer, /loadPlayerArtworkLarge/);
assert.match(appCss, /content-visibility: auto/);
assert.match(appCss, /button:focus-visible/);
assert.match(appCss, /@media \(pointer: coarse\)/);
assert.match(html, /id="analytics-consent-toggle"/);
assert.ok(sw.includes(`mujic-pwa-v${JSON.parse(read('package.json')).version}`), 'The service-worker cache must be versioned with the release.');
assert.match(loader, /discovery-catalog-data\.js/);
assert.match(provider, /MujicModules\?\.ensureOnline/);
assert.doesNotMatch(html, /<script defer src="\.\/js\/online-workspace\.js"><\/script>/);
assert.doesNotMatch(html, /<link rel="stylesheet" href="\.\/css\/online-workspace\.css">/);
assert.doesNotMatch(sw, /'\.\/css\/online-workspace\.css'/);
assert.match(html, /mujic-analytics-consent-v1/);
assert.doesNotMatch(html, /<script async src="https:\/\/www\.googletagmanager\.com\/gtag\/js/);
assert.equal(manifest.orientation, 'any');
assert.match(workspace, /Updating results/);
assert.match(workspace, /IntersectionObserver/);
assert.match(workspace, /Streaming search is temporarily unavailable/);
assert.match(player, /UI\.setMiniPlayerBuffering\?\.\(isOnline, track\)/);
assert.match(settings, /settings-search-input/);
console.log('Performance regression checks passed.');
