const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = file => fs.readFileSync(file,'utf8');
const pkg = JSON.parse(read('package.json'));
const html = read('index.html');
const sw = read('sw.js');
const workspace = read('js/online-workspace.js');
const lyrics = read('js/lyrics.js');
const onlineLyrics = read('js/online-lyrics.js');
const uiLyrics = read('js/ui-lyrics.js');
const uiEvents = read('js/ui-events.js');
const settings = read('js/ui-settings.js');
const appCss = read('css/app.css');
const worker = read('worker/index.js');
const workspaceTests = read('scripts/check-workspaces.js');
assert.equal(pkg.version,'13.2.4');
assert.equal(read('VERSION').trim(),pkg.version);
assert.ok(html.includes('content="13.2.4"'));
assert.ok(sw.includes('mujic-pwa-v13.2.4-cloudflare-edge'));
assert.doesNotMatch(workspace,/query:'Arijit Singh'/i,'home should not hard-code Arijit Singh catalogue requests');
assert.doesNotMatch(workspace,/Arijit Singh romantic songs/i,'generic evening recommendations must not force Arijit queries');
assert.doesNotMatch(html,/data-query="Arijit Singh"/i,'suggested-search chips must not promote a fixed celebrity query');
assert.doesNotMatch(worker,/TRENDING_ARTISTS|LANG_ARTISTS|searchSongs\(ctx, artist/i,'background discovery and queue fallback must not fan out through hard-coded artists');
assert.match(worker,/TRENDING_QUERIES = \['trending songs', 'latest Hindi songs', 'English pop hits'\]/,'trending should use generic cached queries');
assert.match(worker,/cacheable: p => p && Array\.isArray\(p\.queue\)/,'empty recommendation queues should be cached to prevent repeated requests');
assert.match(workspace,/render-v2\|/,'suggestion cache signatures should invalidate old hard-coded discovery results');
assert.match(workspace,/const fresh=sig===suggestState\.sig&&Date\.now\(\)-suggestState\.savedAt<SUGGEST_TTL;/,'negative suggestion results should be cached as well');
assert.ok(workspace.includes("if (!force && homeShelves.quick && Date.now() - (homeShelves.quick?.savedAt || homeLastLoaded || 0) < QUICK_PICKS_TTL) return cached;"),'empty Quick Picks responses should also respect their cooldown');
assert.match(workspace,/getHomeArtistQueries\(Math\.min\(4/,'artist discovery is bounded and history-led');
assert.match(workspace,/HOME_TTL = 45 \* 60 \* 1000/);
assert.match(workspace,/SUGGEST_TTL = 6\*60\*60\*1000/);
assert.match(workspace,/setTimeout\(\(\)=>performSearch\(input\.value\),360\)/);
assert.match(onlineLyrics,/lyrics\/get\?/);
assert.doesNotMatch(onlineLyrics,/X-User-Agent/,'the browser should not send a non-safelisted header that causes an extra CORS preflight');
assert.doesNotMatch(onlineLyrics,/LEGACY_BACKEND}lyrics\?track=/,'the duplicate legacy lyrics wrapper must not issue a second exact lookup');
assert.match(worker,/X-User-Agent': 'Mujic\/13\.2\.4/,'the Worker should identify Mujic to LRCLIB on upstream requests');
assert.match(onlineLyrics,/retryLrclib/);
assert.match(lyrics,/retryLookup: async/);
assert.match(uiLyrics,/attempt<=2/);
assert.match(uiLyrics,/data-action="retry-lyrics"/);
assert.doesNotMatch(uiLyrics,/No lyrics were found\. Lyrics view closed/);
assert.match(uiEvents,/action === 'retry-lyrics'/);
assert.match(uiEvents,/bottomNav\?\.classList\.toggle\('scroll-hidden', shouldCollapse\)/);
assert.match(uiEvents,/if \(delta > 6 && !bottomNav\?\.contains\(document.activeElement\)\) setNavCollapsed\(true\)/);
assert.doesNotMatch(uiEvents,/miniPlayer\.classList\.add\('scroll-hidden'\)/);
assert.match(settings,/motionMode === 'auto' && lowEndActive/);
assert.match(html,/option value="auto">Automatic \(device-aware\)/);
assert.match(appCss,/\.player-lyrics-container \.lyric-line\.active \{ animation: mujic-lyric-focus/);
assert.match(appCss,/prefers-reduced-motion: reduce/);
console.log('v13.2.0 API reduction, lyrics retry, adaptive motion, and mobile mini-player checks passed.');
