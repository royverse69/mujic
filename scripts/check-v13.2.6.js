const fs = require('node:fs');
const assert = require('node:assert/strict');
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const read = f => fs.readFileSync(f, 'utf8');
const css = read('css/app.css');
const events = read('js/ui-events.js');
const player = read('js/ui-player.js');
const html = read('index.html');
const sw = read('sw.js');
assert.equal(pkg.version, '13.2.6');
assert.equal(read('VERSION').trim(), pkg.version);
assert.ok(html.includes(`application-version" content="${pkg.version}"`));
assert.ok(sw.includes(`mujic-pwa-v${pkg.version}-cloudflare-edge`));
assert.match(css, /blur\(76px\) saturate\(1\.5\) brightness\(\.52\)/);
assert.match(css, /radial-gradient\(ellipse at 22% 25%,color-mix\(in srgb,var\(--accent-color\) 62%,transparent\)/);
assert.match(css, /body\.low-end-mode #full-player \.player-bg \{[^}]*filter:none !important;[^}]*opacity:\.22 !important/s);
assert.match(css, /body\.low-end-mode #full-player \.player-bg\[data-background-mode=\"artwork\"\] \{[\s\S]*?background-image:[\s\S]*?linear-gradient/);
assert.match(css, /body\.low-end-mode #full-player \.player-bg::before \{ opacity:\.78 !important/);
assert.match(player, /fullBg\.dataset\.backgroundMode = State\.playerBackground/);
const swipeCss = css.slice(css.indexOf('@keyframes mujic-swipe-art-out-left'));
assert.doesNotMatch(swipeCss, /rotate\(|scale\(/, 'large artwork swipe motion should avoid rotation/scale effects');
assert.match(swipeCss, /animation-duration:150ms/);
assert.match(swipeCss, /animation-duration:190ms/);
assert.match(swipeCss, /@media \(prefers-reduced-motion:reduce\), body\.reduced-motion/);
assert.doesNotMatch(css, /@media \(prefers-reduced-motion:reduce\), body\.low-end-mode, body\.reduced-motion\s*\{[\s\S]{0,250}animation:none/);
assert.match(events, /lowEndMotion\?150:145/);
assert.match(events, /lowEndMotion\?190:235/);
assert.match(player, /window\.requestAnimationFrame\(\(\)=>/);
assert.doesNotMatch(player, /void fullArt\.offsetWidth/, 'swipe entry must not force synchronous layout');
console.log('v13.2.6 checks passed: compositor-friendly swipe, faster low-end timing, reduced-motion support, and clearer static/animated ambience.');
