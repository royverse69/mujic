const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const provider = read('js/online-provider.js');
const downloader = read('js/online-downloader.js');
const backend = read('backend/app.py');
const patch = read('backend/proxy-route-patch.py');
const docs = read('docs/api-integration.md');
const sw = read('sw.js');
const pkg = JSON.parse(read('package.json'));
const html = read('index.html');
const changelog = JSON.parse(read('changlog.json'));
const check = (condition, message) => { if (!condition) throw new Error(message); };
check(pkg.version === '12.0.33' && /application-version" content="12\.0\.33/.test(html), 'App/package version must be 12.0.33.');
check(/mujic-pwa-v12\.0\.33-render-api-media-proxy/.test(sw), 'PWA cache must be versioned for API and media proxy routing.');
check(/const proxyMediaUrl = value =>/.test(provider) && /proxyMediaUrl\(originalUrl\)/.test(provider) && /proxyMediaUrl\(eligible\[0\]\.url\)/.test(provider), 'Playback and download source URLs must use the Render media proxy for known catalogue CDN hosts.');
check(/url: proxyMediaUrl\(/.test(provider) && /OnlineMusic\.proxyMediaUrl\(/.test(downloader), 'Artwork and downloaded cover lookups must use the media proxy when supported.');
check(/@app\.route\("\/media"/.test(backend) && /CATALOGUE_MEDIA_DOMAINS/.test(backend) && /Range/.test(backend) && /allow_redirects=False/.test(backend), 'Bundled backend must proxy supported media with Range forwarding and redirect validation.');
check(/@app\.route\("\/media"/.test(patch) && /CATALOGUE_MEDIA_DOMAINS/.test(patch), 'Merge-safe backend patch must include the media proxy.');
check(/saavncdn\.com/.test(backend) && /jiosaavn\.com/.test(backend), 'Only fixed catalogue CDN domains should be allowed.');
check(/changelog.latest.version === pkg.version/.test(read('scripts/check-v12.0.32.js')) && changelog.latest.version === pkg.version && changelog.version === pkg.version, 'Release metadata/changelog must match current package version.');
check(docs.includes('Render `/media?url=') && /deploy/i.test(docs), 'Docs must explain Render media proxy and deployment requirement.');
console.log('v12.0.33 checks OK: Render media routing, allowlisted domains, byte-range support, redirect validation and release metadata.');
