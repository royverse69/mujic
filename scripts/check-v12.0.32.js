const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const provider = read('js/online-provider.js');
const lyrics = read('js/lyrics.js');
const onlineLyrics = read('js/online-lyrics.js');
const library = read('js/library.js');
const backend = read('backend/app.py');
const patch = read('backend/proxy-route-patch.py');
const sw = read('sw.js');
const pkg = JSON.parse(read('package.json'));
const html = read('index.html');
const docs = read('docs/api-integration.md');
const changelog = JSON.parse(read('changlog.json'));
const check = (condition, message) => { if (!condition) throw new Error(message); };
const browserFiles = [provider, lyrics, onlineLyrics, library];
const htmlVersion = html.match(/<meta name="application-version" content="([^"]+)"/);
check(Boolean(htmlVersion) && pkg.version === htmlVersion[1], 'App/package versions must match.');
check(sw.includes(`mujic-pwa-v${pkg.version}-render-api-media-proxy`), 'Service-worker cache must match the release.');
check(/const LEGACY_BASE = 'https:\/\/gaana-suno-varna-machhar-aajayega\.onrender\.com\/'/.test(provider), 'Catalogue provider must point at the Render backend.');
check(provider.includes("const API_BASE = `${LEGACY_BASE.replace(/\\/$/, '')}/api`;"), 'Documented catalogue requests must use the Render /api route.');
check(!browserFiles.some(text => /saavn\.sumit\.co|saavn\.dev|music-api\.albatross0071\.workers\.dev|lrclib\.net|lyricsplus\.prjktla|lyricsplus-seven\.vercel\.app/i.test(text)), 'Frontend API modules must not call upstream music or lyrics hosts directly.');
check(lyrics.includes('lyrics/get?') && lyrics.includes('lyrics/search?q=') && /\/lyricsplus/.test(lyrics) && /\/v2\/lyrics\/get\?/.test(lyrics), 'Lyrics exact/search and LyricsPlus requests must use Render routes.');
check(/@app\.route\("\/api\/<path:upstream_path>"/.test(backend) && /ALLOWED_CATALOGUE_PREFIXES/.test(backend), 'Bundled backend must provide an allowlisted fixed-origin catalogue proxy.');
check(/@app\.route\("\/lyrics\/search"/.test(backend) && /@app\.route\("\/lyrics\/get"/.test(backend) && /@app\.route\("\/lyricsplus\/v2\/lyrics\/get"/.test(backend), 'Bundled backend must provide fixed-origin lyrics routes.');
check(/@app\.route\("\/api\/<path:upstream_path>"/.test(patch) && /LYRICSPLUS_ORIGINS/.test(patch), 'Merge-safe backend route patch must be included.');
check(/Render backend/i.test(docs) && /deploy/i.test(docs), 'API integration docs must explain the required backend deployment step.');
check(changelog.latest.version === pkg.version && changelog.version === pkg.version, 'Changelog must describe the current release.');
console.log('v12.0.32 checks OK: Render-only API hosts in frontend, catalogue proxy, lyric proxies, deployment notes and cache/version updates.');
